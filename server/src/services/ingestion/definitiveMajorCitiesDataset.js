/**
 * 1. Purges junk scraped POIs from the database
 * 2. Seeds definitive, 100% verified major cities landmarks with top notability scores
 */
export async function seedDefinitiveMajorCitiesDataset() {
  await initDb();
  console.log('[Definitive Catalog] Purging junk commercial and scraped entries...');

  // Deactivate all garbage scraped records
  const purgeSql = `
    UPDATE experiences SET is_active = 0 
    WHERE 
      LOWER(title) LIKE '%convent school%' OR
      LOWER(title) LIKE '%american institute%' OR
      LOWER(title) LIKE '%oyo %' OR
      LOWER(title) LIKE '%collection o%' OR
      LOWER(title) LIKE '%capital o%' OR
      LOWER(title) LIKE '%tailor%' OR
      LOWER(title) LIKE '%titan %' OR
      LOWER(title) LIKE '%titan showroom%' OR
      LOWER(title) LIKE '%timber near%' OR
      LOWER(title) LIKE '%cultural site near%' OR
      LOWER(title) LIKE '%photographer near%' OR
      LOWER(title) LIKE '%unidentified tomb%' OR
      LOWER(title) LIKE '%petrol pump%' OR
      LOWER(title) LIKE '%car wash%' OR
      LOWER(title) LIKE '%hospital%' OR
      LOWER(title) LIKE '%dental clinic%' OR
      LOWER(title) LIKE '%pharmacy%' OR
      LOWER(title) LIKE '%nursing home%' OR
      LOWER(title) LIKE '%bank of %'
  `;
  const purgeResult = await dbRun(purgeSql);
  console.log(`[Definitive Catalog] Deactivated ${purgeResult.changes} junk entries.`);

  let inserted = 0;
  let updated = 0;

  for (const item of MAJOR_CITIES_LANDMARKS) {
    const existing = await dbGet(
      'SELECT id FROM experiences WHERE title = ? OR osm_id = ?',
      [item.title, item.osm_id]
    );

    if (existing) {
      await dbRun(
        `UPDATE experiences SET
           title = ?,
           tagline = ?,
           description = ?,
           category = ?,
           cultural_context = ?,
           state = ?,
           city = ?,
           area_name = ?,
           latitude = ?,
           longitude = ?,
           approx_duration_mins = ?,
           price = ?,
           is_indoor = ?,
           is_rain_safe = ?,
           wheelchair_accessible = ?,
           image_urls = ?,
           tags = ?,
           notability_score = 100,
           source = 'definitive_verified_catalog',
           is_active = 1
         WHERE id = ?`,
        [
          item.title,
          item.tagline,
          item.description,
          item.category,
          item.cultural_context,
          item.state,
          item.city,
          item.area_name,
          item.latitude,
          item.longitude,
          item.approx_duration_mins,
          item.price,
          item.is_indoor,
          item.is_indoor,
          item.wheelchair_accessible,
          item.image_urls,
          item.tags,
          existing.id,
        ]
      );
      updated++;
    } else {
      await dbRun(
        `INSERT INTO experiences (
           title, tagline, description, category, cultural_context,
           state, city, area_name, latitude, longitude,
           approx_duration_mins, price, currency, is_indoor, is_rain_safe,
           is_hidden_gem, is_family_friendly, low_walking, wheelchair_accessible,
           rating, review_count, notability_score, osm_id, osm_type,
           source, image_urls, tags, is_active
         ) VALUES (
           ?, ?, ?, ?, ?,
           ?, ?, ?, ?, ?,
           ?, ?, 'INR', ?, ?,
           0, 1, ?, ?,
           NULL, 0, 100, ?, 'F',
           'definitive_verified_catalog', ?, ?, 1
         )`,
        [
          item.title,
          item.tagline,
          item.description,
          item.category,
          item.cultural_context,
          item.state,
          item.city,
          item.area_name,
          item.latitude,
          item.longitude,
          item.approx_duration_mins,
          item.price,
          item.is_indoor,
          item.is_indoor,
          item.is_indoor,
          item.wheelchair_accessible,
          item.osm_id,
          item.image_urls,
          item.tags,
        ]
      );
      inserted++;
    }
  }

  console.log(`[Definitive Catalog] Seeded ${inserted} new landmarks, updated ${updated} existing to verified state.`);
}

if (process.argv[1]?.endsWith('definitiveMajorCitiesDataset.js')) {
  seedDefinitiveMajorCitiesDataset()
    .then(() => process.exit(0))
    .catch(err => {
      console.error(err);
      process.exit(1);
    });
}
