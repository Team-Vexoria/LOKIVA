/**
 * Seeds all definitive famous places into SQLite
 */
export async function seedDefinitiveFamousPlaces() {
  await initDb();
  let inserted = 0;
  let updated = 0;

  for (const item of DEFINITIVE_FAMOUS_PLACES) {
    const existing = await dbGet('SELECT id FROM experiences WHERE title = ? OR osm_id = ?', [item.title, item.osm_id]);

    if (existing) {
      await dbRun(
        `UPDATE experiences SET
           description = ?,
           cultural_context = ?,
           image_urls = ?,
           price = ?,
           latitude = ?,
           longitude = ?,
           category = ?,
           approx_duration_mins = ?,
           wheelchair_accessible = ?,
           is_indoor = ?,
           source = 'definitive_famous_registry',
           notability_score = 99,
           is_active = 1
         WHERE id = ?`,
        [
          item.description,
          item.cultural_context,
          item.image_urls,
          item.price,
          item.latitude,
          item.longitude,
          item.category,
          item.approx_duration_mins,
          item.wheelchair_accessible,
          item.is_indoor,
          existing.id,
        ]
      );
      updated++;
    } else {
      await dbRun(
        `INSERT INTO experiences (
           title, tagline, description, category, cultural_context,
           state, city, area_name, latitude, longitude,
           approx_duration_mins, price, currency, is_indoor, is_rain_safe,
           is_hidden_gem, is_family_friendly, low_walking, wheelchair_accessible,
           rating, review_count, notability_score, osm_id, osm_type,
           source, image_urls, tags, is_active
         ) VALUES (
           ?, ?, ?, ?, ?,
           ?, ?, ?, ?, ?,
           ?, ?, 'INR', ?, ?,
           0, 1, ?, ?,
           NULL, 0, 99, ?, 'F',
           'definitive_famous_registry', ?, '[]', 1
         )`,
        [
          item.title,
          item.tagline,
          item.description,
          item.category,
          item.cultural_context,
          item.state,
          item.city,
          item.area_name,
          item.latitude,
          item.longitude,
          item.approx_duration_mins,
          item.price,
          item.is_indoor,
          item.is_indoor,
          item.is_indoor,
          item.wheelchair_accessible,
          item.osm_id,
          item.image_urls,
        ]
      );
      inserted++;
    }
  }

  console.log(`[Definitive Registry] Seeded: ${inserted} new, ${updated} updated.`);
}

if (process.argv[1]?.endsWith('definitiveMajorCitiesRegistry.js')) {
  seedDefinitiveFamousPlaces()
    .then(() => process.exit(0))
    .catch(err => {
      console.error(err);
      process.exit(1);
    });
}
