/**
 * Seeds the pan-India cultural dataset into SQLite if not already present
 */
export async function seedPanIndiaCulturalMesh() {
  let inserted = 0;

  for (const item of PAN_INDIA_CULTURAL_DATASET) {
    const existing = await dbGet('SELECT id FROM experiences WHERE osm_id = ?', [item.osm_id]);

    if (!existing) {
      await dbRun(
        `INSERT INTO experiences (
           title, tagline, description, category, cultural_context,
           state, city, area_name, latitude, longitude,
           approx_duration_mins, price, currency, is_indoor, is_rain_safe,
           is_hidden_gem, is_family_friendly, low_walking, wheelchair_accessible,
           rating, review_count, notability_score, osm_id, osm_type,
           source, image_urls, tags, is_active
         ) VALUES (
           ?, ?, ?, ?, ?,
           ?, ?, ?, ?, ?,
           ?, ?, 'INR', ?, ?,
           1, ?, ?, ?,
           NULL, 0, 92, ?, 'N',
           ?, ?, ?, 1
         )`,
        [
          item.title,
          item.tagline,
          item.description,
          item.category,
          item.cultural_context,
          item.state,
          item.city,
          item.area_name,
          item.latitude,
          item.longitude,
          item.approx_duration_mins,
          item.price,
          item.is_indoor,
          item.is_rain_safe,
          item.is_family_friendly,
          item.low_walking,
          item.wheelchair_accessible,
          item.osm_id,
          item.source,
          item.image_urls,
          item.tags,
        ]
      );
      inserted++;
    }
  }

  return { totalSeeded: inserted };
}
